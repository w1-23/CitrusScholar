"""Offline Worker wrapper text and bounded result marker codec."""
import json
import re

MAX_RETURNED_FILES = 24
MAX_TRANSFER_BYTES = 8 * 1024 * 1024
MAX_TRANSFER_FILE_BYTES = 4 * 1024 * 1024
MARKER = "__citrus_execute_result__"
MANIFEST_SCHEMA = "citrus.native-execute/1"


_WRAPPER = '''"""Bounded native-execute wrapper generated by Citrus; do not edit."""
import base64
import hashlib
import json
import os
import shutil
import signal
import stat
import subprocess
import sys

MARKER = @@MARKER@@
COMMAND = @@COMMAND@@
TIMEOUT_SEC = @@TIMEOUT@@
NONCE = @@NONCE@@
MANIFEST = @@MANIFEST@@
SCHEMA = @@SCHEMA@@
BASELINE = @@BASELINE@@
SKIP = @@SKIP@@
ROOTS = ("/workspace", "/outputs")
OUTPUT_ROOT = "/outputs"
MAX_FILE_BYTES = @@MAX_FILE@@
MAX_TOTAL_BYTES = @@MAX_TOTAL@@
MAX_FILES = @@MAX_FILES@@


def emit(code, timed_out, error=""):
    payload = {"exit_code": code, "timed_out": bool(timed_out), "error": str(error)[:64]}
    try:
        sys.stderr.write("\\n" + MARKER + " " + NONCE + " " + json.dumps(payload, separators=(",", ":")) + "\\n")
        sys.stderr.flush()
    except Exception:
        pass


def digest(path):
    value = hashlib.sha256()
    with open(path, "rb") as stream:
        for chunk in iter(lambda: stream.read(262144), b""):
            value.update(chunk)
    return value.hexdigest()


def run():
    try:
        process = subprocess.Popen(["/bin/sh", "-c", COMMAND], cwd="/workspace",
                                   stdin=subprocess.DEVNULL, close_fds=True,
                                   start_new_session=True)
    except Exception as exc:
        return None, False, "spawn_failed:" + type(exc).__name__
    try:
        return process.wait(timeout=TIMEOUT_SEC), False, ""
    except subprocess.TimeoutExpired:
        try:
            os.killpg(os.getpgid(process.pid), signal.SIGKILL)
        except Exception:
            try:
                process.kill()
            except Exception:
                pass
        try:
            process.wait(timeout=10)
        except Exception:
            pass
        return 124, True, ""


def scan(files, dropped, used):
    for root in ROOTS:
        if not os.path.isdir(root):
            continue
        for base, dirs, names in os.walk(root, topdown=True, followlinks=False):
            dirs[:] = sorted(name for name in dirs if not os.path.islink(os.path.join(base, name)))
            for name in sorted(names):
                path = os.path.join(base, name)
                if path in SKIP:
                    continue
                try:
                    info = os.lstat(path)
                    if not stat.S_ISREG(info.st_mode):
                        continue
                    current = digest(path)
                    if BASELINE.get(path) == current:
                        continue
                    if (info.st_size > MAX_FILE_BYTES or used[0] + info.st_size > MAX_TOTAL_BYTES
                            or len(files) >= MAX_FILES):
                        dropped.append({"path": path, "sha256": current,
                                        "size_bytes": info.st_size, "reason": "transfer_limit"})
                        continue
                    with open(path, "rb") as stream:
                        data = stream.read(info.st_size + 1)
                    if len(data) != info.st_size or hashlib.sha256(data).hexdigest() != current:
                        dropped.append({"path": path, "sha256": current,
                                        "size_bytes": info.st_size, "reason": "changed_during_read"})
                        continue
                    used[0] += len(data)
                    files.append({"path": path, "sha256": current, "size_bytes": len(data),
                                  "data": base64.b64encode(data).decode("ascii")})
                except OSError:
                    continue


def purge():
    """The Worker accepts only declared outputs, so /outputs keeps the manifest."""
    try:
        names = sorted(os.listdir(OUTPUT_ROOT))
    except OSError:
        return
    for name in names:
        path = os.path.join(OUTPUT_ROOT, name)
        if path == MANIFEST:
            continue
        try:
            if os.path.isdir(path) and not os.path.islink(path):
                shutil.rmtree(path, ignore_errors=True)
            else:
                os.unlink(path)
        except OSError:
            pass


def main():
    code, timed_out, error = run()
    files, dropped, used = [], [], [0]
    scan(files, dropped, used)
    purge()
    manifest = {"schema": SCHEMA, "nonce": NONCE, "command_exit_code": code,
                "timed_out": timed_out, "error": error, "files": files, "dropped": dropped}
    try:
        with open(MANIFEST, "w", encoding="utf-8") as stream:
            json.dump(manifest, stream, separators=(",", ":"))
    except Exception as exc:
        emit(code, timed_out, "manifest_failed:" + type(exc).__name__)
        return
    emit(code, timed_out, error)


try:
    main()
except BaseException as exc:
    try:
        emit(None, False, "wrapper_failed:" + type(exc).__name__)
    except Exception:
        pass
finally:
    try:
        sys.stdout.flush()
        sys.stderr.flush()
    except Exception:
        pass
sys.exit(0)
'''


def build_wrapper(command, *, timeout, nonce, manifest, baseline, skip):
    """Render the sandbox-side wrapper; JSON literals only, never concatenation."""
    values = {
        "@@MARKER@@": json.dumps(MARKER),
        "@@COMMAND@@": json.dumps(command),
        "@@TIMEOUT@@": str(int(timeout)),
        "@@NONCE@@": json.dumps(nonce),
        "@@MANIFEST@@": json.dumps(manifest),
        "@@SCHEMA@@": json.dumps(MANIFEST_SCHEMA),
        "@@BASELINE@@": json.dumps(baseline, sort_keys=True),
        "@@SKIP@@": json.dumps(sorted(skip)),
        "@@MAX_FILE@@": str(MAX_TRANSFER_FILE_BYTES),
        "@@MAX_TOTAL@@": str(MAX_TRANSFER_BYTES),
        "@@MAX_FILES@@": str(MAX_RETURNED_FILES),
    }
    # Perform one substitution over the template, not over inserted command
    # text. A literal @@TOKEN@@ in a user's command must never be rewritten.
    return re.sub(r"@@[A-Z_]+@@", lambda match: values[match[0]], _WRAPPER)


# -- streaming / parsing helpers ---------------------------------------------


def parse_marker(text, nonce):
    """Return the wrapper's last self-reported status, or ``None``.

    The marker is written after the command exits, so a command that echoes the
    same prefix cannot replace it: the last parseable record wins.
    """
    if not text or not isinstance(text, str) or not isinstance(nonce, str) or not nonce:
        return None
    prefix = MARKER + " " + nonce + " "
    for line in reversed(text.splitlines()):
        if not line.startswith(prefix):
            continue
        try:
            payload = json.loads(line[len(prefix):])
        except ValueError:
            continue
        if not isinstance(payload, dict):
            continue
        code = payload.get("exit_code")
        if code is not None and type(code) is not int:
            continue
        if type(payload.get("timed_out")) is not bool:
            continue
        error = payload.get("error")
        return {"exit_code": code, "timed_out": payload["timed_out"],
                "error": error if isinstance(error, str) else ""}
    return None


def strip_marker(text, nonce):
    """Remove only the wrapper's own marker records from visible output."""
    if not text or not nonce:
        return text
    prefix = MARKER + " " + nonce
    return "".join(line for line in text.splitlines(keepends=True)
                   if not line.lstrip("\r\n").startswith(prefix))
